"""W6 shade, W98 lighting, W39 recolour and W28 balayage: Python -> TypeScript data and parity vectors.

Writes (or with --check, verifies unchanged):
* web/src/engines/shade/generated/data.ts       thresholds, reference shades, lighting presets, brow indices
* web/src/engines/haircolour/generated/levels.ts hair levels, lift per session and toners (ASSUMED data)
* parity/shade-w6.json                          W6/W98 synthetic cases computed by the Python engines
* parity/haircolour-w39-w28.json                W39/W28 cases on drawn coil textures

Synthetic only: drawn faces on the R5 symmetric mesh, drawn coils and seeded random pixels. No photos,
no product data. Generated files are excluded from authored line counts.
Author: John Khan.
"""

def clean(value: object) -> object:
    if isinstance(value, np.ndarray):
        return clean(value.tolist())
    if isinstance(value, (list, tuple)):
        return [clean(v) for v in value]
    if isinstance(value, dict):
        return {str(k): clean(v) for k, v in value.items()}
    if isinstance(value, (np.floating, float)):
        return round(float(value), 9)
    if isinstance(value, np.integer):
        return int(value)
    return value


def data_ts() -> str:
    payload = {
        "thresholds": finder.thresholds(),
        "shades": list(finder.reference_table()),
        "lighting": lighting.presets_data(),
        "brows": list(regions.RIGHT_BROW) + list(regions.LEFT_BROW),
    }
    body = json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
    return ("/** GENERATED by api/scripts/make_parity_shade.py from api/plumb_api/engines/shade/*.json. DO NOT EDIT.\n"
            " * Author: John Khan. */\n"
            f"export const SHADE_DATA = {body} as const;\n")


def levels_ts() -> str:
    body = json.dumps(balayage.levels_data(), separators=(",", ":"), ensure_ascii=False)
    return ("/** GENERATED by api/scripts/make_parity_shade.py from api/plumb_api/engines/haircolour/levels.json."
            " DO NOT EDIT.\n * Author: John Khan. */\n"
            f"export const LEVELS = {body} as const;\n")


def coil_case(period: float, mean: float, size: tuple[int, int] = (40, 48)) -> tuple[np.ndarray, np.ndarray]:
    height, width = size
    yy, xx = np.mgrid[0:height, 0:width].astype(np.float64)
    mask = ((((xx - width / 2) / (width * 0.4)) ** 2 + ((yy - height / 2) / (height * 0.42)) ** 2) <= 1).astype(np.float64)
    phase = 2 * np.pi * ((xx + 0.6 * np.sin(yy / period * 2 * np.pi) * period) / period)
    lum = mean + 12 * np.sin(phase)
    image = np.zeros((height, width, 3), np.uint8)
    image[:] = (200, 210, 220)
    rgb = np.stack([lum, lum * 0.8, lum * 0.6], -1)
    image[mask > 0] = np.clip(np.rint(rgb[mask > 0]), 0, 255).astype(np.uint8)
    return image, mask


def hair_build() -> dict:
    b64 = lambda a: base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()  # noqa: E731
    cases = []
    for period, mean, target in ((10.0, 30.0, [25.0, 3.0, 2.0]), (6.0, 60.0, [60.0, 8.0, 25.0]),
                                 (4.0, 90.0, [45.0, 30.0, 20.0])):
        image, mask = coil_case(period, mean)
        result = recolour.recolour_hair(image, mask, target)
        cases.append({"period": period, "width": image.shape[1], "height": image.shape[0], "image": b64(image),
                      "mask": b64(mask.astype(np.uint8)), "target": target, "out": b64(result.image),
                      "gain": result.gain, "source_lab": list(result.source_lab), "checks": result.checks})
    paints = []
    for period, base_level, target_level, history, toner in ((8.0, 2, 10, "virgin", "none"),
                                                          (5.0, 4, 8, "colour_treated", "ash")):
        image, mask = coil_case(period, 40.0)
        height, width = mask.shape
        strokes = np.zeros(mask.shape)
        strokes[:, width // 2:] = 1
        frame = np.zeros(mask.shape)
        frame[8:40, 6:10] = 1
        result = balayage.paint(image, mask, strokes, target_level=target_level, base_level=base_level,
                                history=history, toner=toner, face_frame=frame, softness_px=3)
        paints.append({"width": width, "height": height, "image": b64(image), "mask": b64(mask.astype(np.uint8)),
                       "strokes": b64(strokes.astype(np.uint8)), "frame": b64(frame.astype(np.uint8)),
                       "base_level": base_level, "target_level": target_level, "history": history, "toner": toner,
                       "out": b64(result.image), "lift": result.lift, "plan": result.plan,
                       "colour_lab": list(result.colour_lab), "checks": result.checks,
                       "measured_level": balayage.measure_base_level(image, mask)})
    plans = [balayage.session_plan(b, t, h) for b, t, h in ((1, 10, "virgin"), (6, 9, "virgin"), (4, 8, "box_dye"),
                                                             (3, 7, "colour_treated"))]
    return clean({"format": "beljour-haircolour-parity/1", "author": "John Khan", "synthetic": True,
                  "tolerance": {"byte": 1, "float": 1e-6, "check": 1e-3}, "recolour": cases, "paint": paints,
                  "plans": plans, "level_lab": {f"{lv}:{t}": balayage.level_lab(lv, t) for lv in (3, 6, 9)
                                                for t in ("none", "pearl", "ash", "violet")}})


def drawn_face(lab: list[float], white_gain: tuple[float, float, float], seed: int) -> dict:
    width, height = 120, 144
    pts = symmetric_face(width, height, face_width=width * 0.55, face_length=height * 0.66)
    oval = regions.region_mask("face_oval", pts, height, width, normalized=False, supersample=2) >= 0.5
    rng = np.random.RandomState(seed)
    skin = cs.lab_to_srgb(np.asarray(lab, dtype=np.float64))
    image = np.zeros((height, width, 3), dtype=np.float64)
    image[:] = (128.0, 128.0, 128.0)
    image[oval] = skin + rng.normal(0, 2.0, (int(oval.sum()), 3))
    lin = cs.decode(np.clip(image, 0, 255)) * np.asarray(white_gain)
    photo = cs.to_bytes(cs.encode(lin))
    background = (~oval).astype(np.uint8)
    result = finder.find_shade(photo, pts, background_mask=background.astype(np.float64)).to_json()
    return {"width": width, "height": height, "points": pts, "image": base64.b64encode(photo.tobytes()).decode(),
            "background": base64.b64encode(background.tobytes()).decode(), "result": result}


def build() -> dict:
    rng = np.random.RandomState(20261023)
    rgbs = rng.randint(0, 256, size=(24, 3)).astype(np.float64)
    labs = [[72, 9, 13], [64, 12, 19], [55, 12, 20], [48, 14, 22], [40, 11, 17], [33, 9, 13], [27, 6, 9],
            [62, 6, 17], [58, 15, 9], [45, 3, 2], [20, 5, 8], [85, 4, 8]]
    zone_sets = []
    for k, (L, a, b) in enumerate(([66, 11, 15], [50, 13, 21], [31, 8, 12], [58, 4, 18])):
        base = cs.lab_to_srgb(np.array([L, a, b], dtype=np.float64))
        zones = {name: np.clip(np.rint(base + rng.normal(0, 3, (140 + 7 * i, 3))), 0, 255)
                 for i, name in enumerate(finder.ZONES)}
        white = finder.white_from_pixels(np.clip(np.rint(rng.normal(128, 4, (40, 3))) * [1.0, 0.95, 0.85], 0, 255),
                                         "grey_world") if k % 2 else finder.NO_WHITE
        zone_sets.append({"zones": zones, "white": white.to_json(),
                          "result": finder.find_from_pixels(zones, white).to_json()})
    white_sets = []
    for scale in ((1.0, 1.0, 1.0), (1.2, 1.0, 0.7), (0.8, 1.0, 1.25), (3.0, 1.0, 0.2)):
        pix = np.clip(np.rint(rng.normal(120, 5, (30, 3)) * np.asarray(scale)), 0, 255)
        white_sets.append({"pixels": pix, "neutral": finder.white_from_pixels(pix, "neutral").to_json()})
    faces = [drawn_face([64, 12, 17], (1.0, 1.0, 1.0), 1), drawn_face([42, 12, 19], (1.15, 1.0, 0.8), 2),
             drawn_face([28, 7, 10], (0.9, 1.0, 1.15), 3)]
    presets = lighting.preset_ids()
    look_items = {"skin": [62, 14, 18], "foundation": [62.5, 13.5, 18.5], "nude lip": [56, 22, 16], "red lip": [45, 55, 35]}
    look_pairs = [{"a": "skin", "b": "foundation", "kind": "match"}, {"a": "skin", "b": "nude lip", "kind": "contrast"},
                  {"a": "skin", "b": "red lip", "kind": "contrast"}]
    scene = lighting.estimate_white(np.clip(np.rint(rng.normal(120, 3, (40, 3)) * [1.1, 1.0, 0.8]), 0, 255))
    small = rng.randint(0, 256, size=(6, 5, 3)).astype(np.uint8)
    return clean({
        "format": "beljour-shade-w6-parity/1", "author": "John Khan", "synthetic": True,
        "tolerance": {"lab": 1e-6, "delta_e": 1e-6, "matrix": 1e-9, "face_lab": 0.05, "byte": 1},
        "rgb_to_lab": [{"rgb": v, "lab": cs.srgb_to_lab(v)} for v in rgbs],
        "lab_to_rgb": [{"lab": v, "rgb": cs.lab_to_srgb(np.asarray(v, dtype=np.float64))} for v in labs],
        "classify": [{"lab": v, "undertone": finder.undertone_of(v), "depth": finder.depth_band(v[0]),
                      "match": [{"id": m["id"], "delta_e": m["delta_e"]} for m in finder.match_shades(v)[:3]]}
                     for v in labs],
        "white": white_sets,
        "zones": zone_sets,
        "faces": faces,
        "lighting": {
            "planckian": [{"cct": t, "xy": lighting.planckian_xy(t)} for t in (1800, 2400, 2700, 3500, 4000, 5000, 9000)],
            "daylight": [{"cct": t, "xy": lighting.daylight_xy(t)} for t in (4500, 5500, 6504, 7500, 12000)],
            "duv": [{"cct": 4100, "duv": 0.004, "xy": lighting.with_duv(4100, 0.004)},
                    {"cct": 3000, "duv": -0.003, "xy": lighting.with_duv(3000, -0.003)}],
            "matrices": {pid: lighting.appearance_matrix(lighting.preset(pid)) for pid in presets},
            "relight": [{"lab": v, "by_preset": {pid: lighting.relight_lab(v, pid) for pid in presets}} for v in labs[:6]],
            "scene_white": scene,
            "look": lighting.simulate_look(look_items, look_pairs, presets=presets).to_json(),
            "look_scene": lighting.simulate_look(look_items, look_pairs, scene_white=scene).to_json(),
            "image": {"width": 5, "height": 6, "rgb": small,
                      "evening": lighting.relight_image(small, "evening"),
                      "office_scene": lighting.relight_image(small, "office", scene_white=scene)},
        },
    })


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {DATA_TS: data_ts(), PARITY: json.dumps(build(), separators=(",", ":"), sort_keys=True) + "\n",
               LEVELS_TS: levels_ts(),
               HAIR_PARITY: json.dumps(hair_build(), separators=(",", ":"), sort_keys=True) + "\n"}
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"W6/W98/W39/W28 generated file drift ({path.relative_to(ROOT)}): "
                                 "run python api/scripts/make_parity_shade.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(f"W6/W98/W39/W28 data and parity {'in sync' if args.check else 'written'}")


if __name__ == "__main__":
    main()

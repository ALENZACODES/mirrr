// FX1 recipe schema v1 in the browser: the generated catalogue validates, ranks follow §2.22,
// the women-first defaults hold, and the validator catches each kind of broken recipe.
// Author: John Khan.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import * as S from "../dist/js/filters/recipe/schema.js";
import { FilterCatalogue, catalogue } from "../dist/js/filters/recipe/registry.js";
import { CATALOGUE } from "../dist/js/filters/data/generated/recipes.js";

const clone = (x) => JSON.parse(JSON.stringify(x));
const recipe = (id) => clone(catalogue().get(id));
const problems = (r) => S.checkRecipe(r, catalogue().addons);

test("the generated catalogue validates and holds the 61 FX1 looks", () => {
  assert.deepEqual(catalogue().problems(), []);
  assert.equal(catalogue().recipes.length, 61);
  const ids = new Set(catalogue().ids());
  for (let i = 1; i <= 43; i++) assert.ok(ids.has(`C${String(i).padStart(2, "0")}`), `C${i}`);
  for (let i = 1; i <= 6; i++) assert.ok(ids.has(`M0${i}`));
  for (const id of ["C50", "C53", "C54", "C55", "C63", "C77", "C93", "C102", "C103", "C105", "C106", "C107"]) assert.ok(ids.has(id), id);
});

test("the generated file says where it comes from and is not edited by hand", () => {
  const text = readFileSync(new URL("../src/filters/data/generated/recipes.ts", import.meta.url), "utf8");
  assert.match(text, /GENERATED by scripts\/sync_filters\.py/);
  assert.equal(CATALOGUE.format, S.FORMAT);
});

test("strip order is the §2.22 rank: Deauville first, scores never rise", () => {
  const ranked = catalogue().recipes;
  assert.equal(ranked[0].id, "C01");
  assert.deepEqual(ranked.slice(0, 6).map((r) => r.id), ["C01", "C02", "C03", "C05", "C06", "C07"]);
  for (let i = 1; i < ranked.length; i++) {
    assert.ok(ranked[i].rank > ranked[i - 1].rank);
    assert.ok(ranked[i].like.score <= ranked[i - 1].like.score, `${ranked[i].id} after ${ranked[i - 1].id}`);
  }
  const rows = new Map(CATALOGUE.ranking.map((r) => [r.id, r]));
  assert.equal(rows.get("O01").rank, 3, "the ranking keeps other rounds' places (crowns at 3)");
  assert.equal(rows.get("C27").rank, 60);
});

test("women-first defaults: 30, guard on, no geometry; Fontainebleau and Talloires keep her", () => {
  for (const r of catalogue().recipes) {
    assert.equal(r.defaults.strength, 30, r.id);
    assert.equal(r.defaults.guard, true, r.id);
    assert.equal(r.limits.geometry, "none");
    assert.equal(r.limits.simulationLabel, false);
    assert.ok(!/clinic|flaw|fix your/i.test(r.description), `${r.id} copy`);
  }
  assert.equal(catalogue().get("C28").defaults.backgroundOnly, true);
  assert.equal(catalogue().get("C39").defaults.protectSkin, true);
});


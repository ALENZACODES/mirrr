test("the validator catches each kind of broken recipe", () => {
  assert.deepEqual(problems(recipe("C08")), []);
  const cases = [
    [(r) => { r.id = "c8"; }, /id must look like/],
    [(r) => { r.tab = "Clinic"; }, /unknown tab/],
    [(r) => { r.defaults.strength = 60; }, /start at 30/],
    [(r) => { r.description = "x".repeat(81); }, /description/],
    [(r) => { r.stages.push({ op: "colour.sparkle", params: {} }); }, /unknown op/],
    [(r) => { r.stages.push({ op: "colour.exposure", params: { ev: 9 } }); }, /outside/],
    [(r) => { r.stages.push({ op: "colour.tint", params: { hue: 1, amount: 0.01, lips: 1 } }); }, /face region/],
    [(r) => { r.stages.push({ op: "colour.greyWorld", params: { castA: 0.1 } }); }, /measured from the photo/],
    [(r) => { r.stages.push({ op: "colour.exposure", params: {}, scale: "wobble" }); }, /scale must be/],
    [(r) => { r.limits.geometry = "fun"; }, /only in the Fun tab/],
    [(r) => { r.needs.depth = true; }, /ruling R3/],
    [(r) => { r.provenance.writtenFrom = "another app"; }, /filters-plan\.md/],
    [(r) => { r.defaults.addons.push({ id: "sparkle", amount: 10 }); }, /unknown add-on/],
    [(r) => { r.presets = [{ name: "A", patch: { nope: {} } }]; }, /unknown stage/],
    [(r) => { r.presets = [{ name: "A", pending: ["border soon"] }]; }, /which round/],
    [(r) => { r.stages.push({ op: "colour.curve", params: { master: [[0, 0], [0, 1]] } }); }, /strictly increase/],
    [(r) => { r.stages.push({ op: "colour.hsl", params: { bands: { teal: { hue: 1 } } } }); }, /unknown band/],
    [(r) => { r.stages.push({ op: "colour.channelMixer", params: { matrix: [[1, 0], [0, 1]] } }); }, /3 x 3/],
    [(r) => { r.seed = "random"; }, /seed/],
  ];
  for (const [change, expected] of cases) {
    const r = recipe("C08");
    change(r);
    const found = problems(r);
    assert.ok(found.some((p) => expected.test(p)), `${expected} not in ${JSON.stringify(found)}`);
  }
  const missing = recipe("C08"); delete missing.stages;
  assert.deepEqual(problems(missing), ["C08: missing field stages"]);
});

test("catalogue-level rules: duplicate ids, names, ranks and ranking drift", () => {
  const data = clone(CATALOGUE);
  data.recipes.push({ ...clone(data.recipes[0]), name: data.recipes[1].name.toUpperCase() });
  const found = S.checkCatalogue(data);
  assert.ok(found.some((p) => /id used 2 times/.test(p)));
  assert.ok(found.some((p) => /rank 1 is also/.test(p)));
  const drift = clone(CATALOGUE); drift.ranking.find((r) => r.id === "C08").rank = 99;
  assert.ok(S.checkCatalogue(drift).some((p) => /differs from the ranking/.test(p)));
  const addon = clone(CATALOGUE);
  const pending = addon.addons.find((a) => a.id === "grain");
  pending.built = false;
  pending.manualOnly = false;
  pending.round = "soon";
  assert.ok(S.checkCatalogue(addon).some((p) => /names its round/.test(p)));
  assert.deepEqual(S.checkCatalogue({ ...clone(CATALOGUE), format: "x" }), ["catalogue: unknown format"]);
});

test("the eight original finishing add-ons have declared activation rules", () => {
  const built = [...catalogue().addons.values()].filter((a) => a.built).map((a) => a.id);
  assert.deepEqual(built, ["border", "centre-light", "fade", "glow", "grain",
    "halation", "structure", "vignette"]);
  const manual = [...catalogue().addons.values()].filter((a) => a.manualOnly).map((a) => a.id);
  assert.deepEqual(manual, ["grain", "structure"]);
  for (const a of catalogue().addons.values()) {
    assert.equal(a.round, a.id === "fade" ? "FX1" : "FX2", a.id);
  }
});

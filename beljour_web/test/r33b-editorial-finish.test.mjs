test("schema refuses missing, invalid, and unapproved grade keys", () => {
  const baseline = clone(all.get("C08"));
  const cases = [
    [undefined, /missing field editorial/],
    [null, /must declare/],
    [{}, /editorial\.family/],
    [{ family: "Moonlight", light: "Window" }, /editorial\.family/],
    [{ family: "Masthead", light: "Flash" }, /editorial\.light/],
    [{ family: "Masthead", light: "Window", extra: 1 }, /only declares/],
    ["Masthead/Window", /must declare/],
  ];
  for (const [grade, expected] of cases) {
    const invalid = clone(baseline);
    if (grade === undefined) delete invalid.editorial;
    else invalid.editorial = grade;
    assert.ok(checkRecipe(invalid, all.addons).some((p) => expected.test(p)), expected.toString());
  }
});

test("filter inspector lists the family and intended light without changing strength", () => {
  for (const rec of TOP) {
    const parameters = defaultFilterParams(rec.id);
    const c = filterControls({ parameters });
    assert.equal(c.family, rec.editorial.family);
    assert.equal(c.light, rec.editorial.light);
    assert.ok(c.hint.includes(rec.editorial.family));
    assert.ok(c.hint.includes(`${rec.editorial.light} light`));
    assert.ok(c.looks.find((choice) => choice.value === rec.id).label.includes(rec.editorial.family));
    assert.equal(filterLevel({ strength: rec.defaults.strength, parameters }), fromPercent(rec.defaults.strength));
    assert.equal(c.identityLock, true);
  }
});

test("metadata changes the label only, not preview mathematics", () => {
  const rec = clone(all.get("C08"));
  const before = plan(rec, {}, true);
  rec.editorial = { family: "Heritage", light: "Evening" };
  const after = plan(rec, {}, true);
  assert.deepEqual(before, after);
  const { image, masks } = synthetic(40, 47);
  const first = render(image, "C08", {}, masks);
  const second = render(image, rec, {}, masks);
  equalBytes(first.image.data, second.image.data, "editorial grade is not a hidden tint");
});

test("halation and border are genuine local add-ons and not pending labels", () => {
  const names = ["halation", "border"];
  for (const [name, kernel] of [["halation", "spatial.halation"], ["border", "light.border"]]) {
    const info = all.addons.get(name);
    assert.equal(info.built, true);
    assert.equal(info.stage.op, kernel);
    assert.equal(info.round, "FX2");
    assert.ok(BUILT_ADDON_IDS.includes(name));
    assert.equal(checkParams(op(kernel), info.stage.params, kernel).length, 0);
  }
  assert.ok(names.every((id) => all.addons.has(id)));
});

test("Halation and Border are both represented in the committed Python parity data", () => {
  for (const name of ["spatial.halation", "light.border"]) {
    const vectors = P.spatial.filter((v) => v.op === name);
    assert.ok(vectors.length >= 2, `${name} needs full-frame and offset-tile vectors`);
    assert.ok(vectors.some((v) => v.frame[2] !== 0));
  }
});

test("three existing Border presets replace pending labels with actual geometry", () => {
  for (const [id, name, tone] of [["C41", "Rosé", -1], ["M02", "White border", 1],
    ["C43", "Print border", 1]]) {
    const recipe = all.get(id);
    const preset = recipe.presets.find((p) => p.name === name);
    assert.ok(preset, `${id}/${name}`);
    assert.ok(!preset.pending?.includes("border FX2"));
    assert.equal(preset.append.find((s) => s.op === "light.border").params.tone, tone);
    const prepared = plan(recipe, { preset: name }, true);
    assert.ok(prepared.stages.some((stage) => stage.op === "light.border"));
    assert.ok(!prepared.pending.some((part) => part.includes("border")));
  }
});

test("zero-strength and zero-amount are reversible for the added effects", () => {
  const { image, masks } = synthetic(40, 48);
  for (const name of ["halation", "border"]) {
    const untouched = Uint8Array.from(image.data);
    const none = render(image, "C08", setting(name, 0), masks);
    const enabled = render(image, "C08", setting(name, 90), masks);
    assert.equal(none.plan.identity, true);
    assert.equal(enabled.plan.identity, false);
    equalBytes(none.image.data, untouched, `${name} neutral`);
    assert.ok(changed(enabled.image.data, untouched) > 0, `${name} should be a working effect`);
    equalBytes(image.data, untouched, "the source stays private");
  }
});

for (const name of ["halation", "border"]) {
  for (const guard of [true, false]) {
    test(`${name} whole-frame and tiled exports match, skin guard ${guard}`, () => {
      const { image, masks } = synthetic(79, 67);
      const options = { strength: 30, guard, addons: { [name]: 90 } };
      const whole = render(image, "C09", options, masks, [38, 33]);
      for (const size of [16, 23, 32]) {
        const tiled = new TiledRender(image, "C09", options, masks, [38, 33], size).runAll();
        equalBytes(tiled.image.data, whole.image.data, `${name}/${size} final`);
        equalBytes(tiled.look.data, whole.look.data, `${name}/${size} look`);
        assert.deepEqual(tiled.plan.stages, whole.plan.stages);
        assert.equal(tiled.plan.guard, guard);
      }
    });
  }

  test(`${name} optional toggle never switches off Protect Skin`, () => {
    const { image, masks } = synthetic(51, 59);
    const out = render(image, "C01", { strength: 100, guard: false, protectSkin: true,
      addons: { [name]: 100 } }, masks);
    for (let pixel = 0; pixel < masks.skin.data.length; pixel++) {
      if (masks.skin.data[pixel] !== 1) continue;
      for (let channel = 0; channel < 3; channel++) {
        assert.equal(out.image.data[pixel * 3 + channel], image.data[pixel * 3 + channel]);
      }
    }
  });

  test(`${name} keeps the pixel and mask buffers unchanged for repeat renders`, () => {
    const { image, masks } = synthetic(43, 55);
    const frozenImage = Uint8Array.from(image.data);
    const frozenSkin = Float32Array.from(masks.skin.data);
    const options = setting(name, 75, false);
    const a = render(image, "C08", options, masks);
    const b = render(image, "C08", options, masks);
    equalBytes(a.image.data, b.image.data, `${name} deterministic`);
    equalBytes(image.data, frozenImage, `${name} input immutable`);
    equalBytes(masks.skin.data, frozenSkin, `${name} mask immutable`);
    assert.notStrictEqual(a.image.data.buffer, image.data.buffer);
  });
}

test("old Fade-only layers retain old settings and new controls start disabled", () => {
  const legacy = settingsFor({ parameters: { recipe: "C08", addon_fade: 31 }, strength: 45 });
  assert.deepEqual(legacy.addons, { fade: 31 });
  const fresh = settingsFor({ parameters: defaultFilterParams("C08"), strength: 45 });
  assert.equal(fresh.addons.border, 0);
  assert.equal(fresh.addons.halation, 0);
  assert.equal(fresh.identityLock, true);
});

export function lookupTerm(term) {
  const allGlossaries = [
    GLOSSARY_A, GLOSSARY_B, GLOSSARY_C, GLOSSARY_D, GLOSSARY_E,
    GLOSSARY_F, GLOSSARY_G, GLOSSARY_H, GLOSSARY_I, GLOSSARY_JK,
    GLOSSARY_L, GLOSSARY_M, GLOSSARY_N, GLOSSARY_O, GLOSSARY_P,
    GLOSSARY_R, GLOSSARY_S, GLOSSARY_T, GLOSSARY_UZ,
  ];

  const searchTerm = term.toLowerCase().replace(/[_\s-]/g, '_');
  for (const glossary of allGlossaries) {
    for (const [key, entry] of Object.entries(glossary)) {
      if (key.toLowerCase() === searchTerm ||
          entry.term.toLowerCase().includes(term.toLowerCase())) {
        return entry;
      }
    }
  }
  return null;
}


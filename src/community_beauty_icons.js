// ─── UNIFIED API ──────────────────────────────────────────────────────────────

export const ALL_COMMUNITY_ICONS = {
  'west-african': WEST_AFRICAN_ICONS,
  'south-asian': SOUTH_ASIAN_ICONS,
  'arab': ARAB_ICONS,
  'caribbean': CARIBBEAN_ICONS,
  'latina': LATINA_ICONS,
  'east-asian': EAST_ASIAN_ICONS,
  'black-american': BLACK_AMERICAN_ICONS,
  'east-african': EAST_AFRICAN_ICONS,
};

export function getIconsForCommunity(communityId) {
  return ALL_COMMUNITY_ICONS[communityId] || [];
}

export function getAllIcons() {
  return Object.entries(ALL_COMMUNITY_ICONS).flatMap(([community, icons]) =>
    icons.map(icon => ({ ...icon, community }))
  );
}

export function getIconByLookCategory(lookCategory) {
  return getAllIcons().filter(icon =>
    icon.lookCategory === lookCategory
  );
}

export function getIconSignatureTechniques(communityId, iconName) {
  const icons = ALL_COMMUNITY_ICONS[communityId] || [];
  const icon = icons.find(i => i.name.toLowerCase().includes(iconName.toLowerCase()));
  return icon ? icon.techniques : null;
}

export function searchIcons(query) {
  const q = query.toLowerCase();
  return getAllIcons().filter(icon =>
    icon.name.toLowerCase().includes(q) ||
    icon.signatureLook?.toLowerCase().includes(q) ||
    icon.makeupPhilosophy?.toLowerCase().includes(q) ||
    icon.lookCategory?.toLowerCase().includes(q)
  );
}

export const BEAUTY_ICONS_STATS = {
  totalIcons: getAllIcons().length,
  communitiesRepresented: Object.keys(ALL_COMMUNITY_ICONS).length,
  lookCategories: [...new Set(getAllIcons().map(i => i.lookCategory))],
};

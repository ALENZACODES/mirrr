// ─── API ──────────────────────────────────────────────────────────────────────

export function getDewySkinOverview() { return DEWY_SKIN_OVERVIEW; }
export function getDewySkincare(ingredient) {
  return ingredient ? DEWY_SKINCARE.key_ingredients[ingredient] : DEWY_SKINCARE;
}
export function getDewySkinMakeup(section) {
  return section ? DEWY_MAKEUP[section] : DEWY_MAKEUP;
}
export function getGlowFinish(type) {
  return type ? GLOW_FINISHES[type] : GLOW_FINISHES;
}
export function getDewySkinForFitzpatrick(type) {
  return type ? DEWY_BY_FITZPATRICK[type] : DEWY_BY_FITZPATRICK;
}
export function getEthnicGlowTradition(communityId) {
  const key = communityId?.replace('-', '_');
  return ETHNIC_GLOW_TRADITIONS[key] || Object.values(ETHNIC_GLOW_TRADITIONS);
}


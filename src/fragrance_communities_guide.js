export function getIncenseBeauty(community) {
  if (community) {
    const key = community.toLowerCase().replace(/[\s-]/g, '_');
    return INCENSE_BEAUTY.types_by_community[key] || INCENSE_BEAUTY;
  }
  return INCENSE_BEAUTY;
}
